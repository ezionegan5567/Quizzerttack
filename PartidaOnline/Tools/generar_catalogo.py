#!/usr/bin/env python3
"""
Genera los datos que el servidor necesita a partir del código del juego, para no
mantener dos copias a mano:

  - Core/Catalogo.Generado.cs   <- Assets/Scripts/Combate/DatosFacciones.cs + MazoFaccion.cs
  - Core/Preguntas.Generado.cs  <- Assets/Scripts/Combate/QuizHabilidades.cs

Uso (desde la raíz del repo):  python PartidaOnline/Tools/generar_catalogo.py

Si cambias héroes, habilidades o preguntas en Unity, vuelve a ejecutarlo y
redespliega el módulo. Nunca edites los *.Generado.cs a mano.
"""
import re
import sys
from pathlib import Path

RAIZ = Path(__file__).resolve().parents[2]
COMBATE = RAIZ / "Assets" / "Scripts" / "Combate"
SALIDA = RAIZ / "PartidaOnline" / "Core"

# Clave interna de DatosFacciones -> id estable (mismos ids que Tienda/TablaRivales.cs)
IDS = {
    "lanza": "lanza_con_escudo", "hacha": "guerrero_del_hacha", "doshachas": "guerrero_dos_hachas",
    "lobo": "hombre_lobo", "cura": "curandero", "muneco": "muneco_poseido", "draco": "draconiano",
}


def cs(texto: str) -> str:
    return '"' + texto.replace("\\", "\\\\").replace('"', '\\"') + '"'


def partir_argumentos(texto: str):
    """Divide por comas de primer nivel (respeta comillas y paréntesis)."""
    partes, actual, nivel, en_texto = [], "", 0, False
    for c in texto:
        if c == '"':
            en_texto = not en_texto
        if not en_texto:
            if c == "(":
                nivel += 1
            elif c == ")":
                nivel -= 1
            elif c == "," and nivel == 0:
                partes.append(actual.strip())
                actual = ""
                continue
        actual += c
    if actual.strip():
        partes.append(actual.strip())
    return partes


def generar_catalogo() -> str:
    codigo = (COMBATE / "DatosFacciones.cs").read_text(encoding="utf-8")
    mazo = (COMBATE / "MazoFaccion.cs").read_text(encoding="utf-8")

    # Stats: { "bufeador", new int[]{ 90, 15 } }
    stats = {m[0]: (int(m[1]), int(m[2])) for m in re.findall(
        r'\{\s*"(\w+)",\s*new int\[\]\{\s*(\d+),\s*(\d+)\s*\}\s*\}', codigo)}

    # Héroes: { "clave", new DatosPeleador("Display", new InfoHabilidad[]{ ... })[, pasiva] },
    heroes = {}
    for m in re.finditer(r'\{\s*"(\w+)",\s*new DatosPeleador\("([^"]+)",\s*new InfoHabilidad\[\]\{(.*?)\}\s*(?:,\s*EfectoH\.\w+)?\)\s*\}', codigo, re.S):
        clave, display, cuerpo = m.group(1), m.group(2), m.group(3)
        habilidades = []
        for h in re.finditer(r'H\((.*?)\),\s*(?:\n|$)', cuerpo + "\n", re.S):
            args = partir_argumentos(h.group(1))
            nombre = args[0].strip('"')
            efecto = args[1].replace("EfectoH.", "")
            objetivo = args[2].replace("ObjetivoH.", "")
            resto = args[3:]
            valor = int(resto[0]) if len(resto) > 0 else 0
            duracion = int(resto[1]) if len(resto) > 1 else 0
            efecto2 = resto[2].replace("EfectoH.", "") if len(resto) > 2 else "Ninguno"
            objetivo2 = resto[3].replace("ObjetivoH.", "") if len(resto) > 3 else "Ninguno"
            valor2 = int(resto[4]) if len(resto) > 4 else 0
            duracion2 = int(resto[5]) if len(resto) > 5 else 0
            habilidades.append((nombre, efecto, objetivo, valor, duracion, efecto2, objetivo2, valor2, duracion2))
        heroes[clave] = (display, habilidades)

    # Facciones: { "F1", new string[]{ "Bufeador", ... } }
    facciones = {}
    por_display = {v[0].lower(): k for k, v in heroes.items()}
    # MazoFaccion usa nombres de carta que no siempre coinciden con el nombre de DatosFacciones
    por_display.update({"guerrero del hacha": "hacha", "lanza con escudo": "lanza", "guerrero dos hachas": "doshachas",
                        "hombre lobo": "lobo", "curandero": "cura", "muneco poseido": "muneco", "draconiano": "draco"})
    for m in re.finditer(r'\{\s*"(F\d)",\s*new string\[\]\{(.*?)\}\s*\}', mazo, re.S):
        nombres = re.findall(r'"([^"]+)"', m.group(2))
        facciones[m.group(1)] = [por_display[n.lower()] for n in nombres]

    if len(heroes) != 20 or len(facciones) != 4 or any(len(v) != 5 for v in facciones.values()):
        sys.exit(f"Catálogo inesperado: {len(heroes)} héroes, facciones {list(facciones)}. Revisa los patrones.")

    faccion_de = {clave: f for f, claves in facciones.items() for clave in claves}
    lineas = ["// <auto-generated> Lo produce PartidaOnline/Tools/generar_catalogo.py. No lo edites a mano. </auto-generated>",
              "namespace QuizzerMatch;", "", "public static partial class Catalogo", "{",
              "    static partial void Cargar(List<HeroeDef> destino)", "    {"]
    for f in sorted(facciones):
        for clave in facciones[f]:
            display, habs = heroes[clave]
            vida, ataque = stats[clave]
            hid = IDS.get(clave, clave)
            lineas.append(f'        destino.Add(new HeroeDef({cs(hid)}, {cs(display)}, {cs(faccion_de[clave])}, {vida}, {ataque}, new[]')
            lineas.append("        {")
            for (n, e, o, v, d, e2, o2, v2, d2) in habs:
                lineas.append(f"            new Habilidad({cs(n)}, Efecto.{e}, Objetivo.{o}, {v}, {d}, Efecto.{e2}, Objetivo.{o2}, {v2}, {d2}),")
            lineas.append("        }));")
    lineas += ["    }", "}", ""]
    return "\n".join(lineas)


def generar_preguntas() -> str:
    codigo = (COMBATE / "QuizHabilidades.cs").read_text(encoding="utf-8")
    preguntas = re.findall(
        r'new Pregunta\(\)\{\s*pregunta\s*=\s*"([^"]+)",\s*respuestas\s*=\s*new string\[\]\{([^}]*)\},\s*indiceCorrecta\s*=\s*(\d)\s*\}', codigo)
    if len(preguntas) < 10:
        sys.exit(f"Solo se encontraron {len(preguntas)} preguntas. Revisa el patrón.")
    lineas = ["// <auto-generated> Lo produce PartidaOnline/Tools/generar_catalogo.py. No lo edites a mano. </auto-generated>",
              "namespace QuizzerMatch;", "",
              "public static partial class BancoPreguntas", "{",
              "    static partial void Cargar(List<PreguntaDef> destino)", "    {"]
    for i, (texto, respuestas, correcta) in enumerate(preguntas):
        opciones = re.findall(r'"([^"]*)"', respuestas)
        lineas.append(f"        destino.Add(new PreguntaDef({i}, {cs(texto)}, new[] {{ {', '.join(cs(o) for o in opciones)} }}, {correcta}));")
    lineas += ["    }", "}", ""]
    return "\n".join(lineas)


if __name__ == "__main__":
    SALIDA.mkdir(parents=True, exist_ok=True)
    (SALIDA / "Catalogo.Generado.cs").write_text(generar_catalogo(), encoding="utf-8")
    (SALIDA / "Preguntas.Generado.cs").write_text(generar_preguntas(), encoding="utf-8")
    print("Generado: Catalogo.Generado.cs y Preguntas.Generado.cs")
